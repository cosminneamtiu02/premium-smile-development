// The REAL stylesheet, compiled by the same Tailwind pipeline the site uses.
// The "one shape, two faces" pin below is meaningless without it: 3rem is a
// COMPUTED length, and the whole promise of this atom is that the letters
// face and the picture face resolve to the same box — never a class name.
// tests/setup/components.ts loads no CSS globally; the per-file import is the
