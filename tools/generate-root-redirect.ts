// Generates out/index.html — the root "/" locale redirect stub (brief §5:
// cookie → navigator.language → default) — FROM src/i18n/locales.ts and
// src/i18n/href.ts, so neither the locale list nor the URL shape can drift from
// the modules that own them. Runs as the last step of `npm run build` on plain
// Node (24+ strips types natively). Deterministic: same inputs ⇒ same bytes.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { localeHref } from '../src/i18n/href.ts';
import { defaultLocale, locales, nativeNames } from '../src/i18n/locales.ts';

const outDir = join(process.cwd(), 'out');
if (!existsSync(outDir)) {
  console.error(
    'out/ not found — run `next build` first (this runs inside `npm run build`).',
  );
  process.exit(1);
}

const messages = JSON.parse(
  readFileSync(
    join(process.cwd(), 'src', 'messages', `${defaultLocale}.json`),
    'utf8',
  ),
) as { common: { siteName: string } };

// Interim GitHub Pages serves under /<repo>/ (§15.2 amended 2026-08-02):
// PAGES_BASE_PATH prefixes every path; NOINDEX=1 (or STAGING=1) keeps the
// github.io copy out of Google until the real domain is attached. `base` is
// read here for the log line only — every URL in the page comes from localeHref
// (§15.13), including the script's.
const base = process.env.PAGES_BASE_PATH ?? '';
const noindex = process.env.NOINDEX === '1' || process.env.STAGING === '1';

// BOTH shapes come from the same builder (org review D12). The inline script
// cannot CALL it — it is emitted as text and runs in the visitor's browser,
// where no module of ours exists — so the call happens here, at build time, and
// what ships is its RESULT: a locale → href table the script only indexes into.
// The visitor's browser therefore performs no URL arithmetic of its own, and
// href.ts is left with no second spelling to stay in step with.
// The tuple annotation is load-bearing: without it the entries infer as
// string[][] and Object.fromEntries falls to its `any` overload.
const hrefs = Object.fromEntries(
  locales.map((l): [string, string] => [l, localeHref(l, '/')]),
);

// Each link is IN its own language ("Deutsch", « Français »), so it carries
// its own lang — SC 3.1.2: without it a screen reader pronounces "Deutsch"
// with the page's Romanian voice — and hreflang, the destination's language
// (same code both times).
const links = locales
  .map(
    (l) =>
      `      <li><a href="${hrefs[l]}" lang="${l}" hreflang="${l}">${nativeNames[l]}</a></li>`,
  )
  .join('\n');

const html = `<!doctype html>
<html lang="${defaultLocale}">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${messages.common.siteName}</title>${noindex ? '\n    <meta name="robots" content="noindex" />' : ''}
    <!--
      GENERATED by tools/generate-root-redirect.ts from src/i18n/locales.ts
      (the locales) and src/i18n/href.ts (every URL below) — do not edit by
      hand. Root "/" redirect (brief §5): cookie → navigator.language →
      /${defaultLocale}. The cookie is only ever SET elsewhere on explicit user
      click (§8.7); this script merely reads it. No IP/geolocation, ever
      (§8.6).
    -->
    <script>
      (function () {
        var hrefs = ${JSON.stringify(hrefs)};
        var locales = ${JSON.stringify([...locales])};
        var target = null;
        var m = document.cookie.match(/(?:^|;\\s*)NEXT_LOCALE=([a-z]{2})/);
        if (m && locales.indexOf(m[1]) !== -1) target = m[1];
        if (!target) {
          var prefs = navigator.languages || [navigator.language || ''];
          for (var i = 0; i < prefs.length && !target; i++) {
            var p = String(prefs[i]).slice(0, 2).toLowerCase();
            if (locales.indexOf(p) !== -1) target = p;
          }
        }
        location.replace(hrefs[target || '${defaultLocale}']);
      })();
    </script>
  </head>
  <body>
    <!-- Visible on purpose (not <noscript>): JS users are redirected before
         paint; no-JS users get real navigation; crawlers and the linkinator
         gate get a followable entry into every locale tree (§13). -->
    <ul>
${links}
    </ul>
  </body>
</html>
`;

writeFileSync(join(outDir, 'index.html'), html);
console.log(
  `out/index.html generated for [${locales.join(', ')}], default "${defaultLocale}", base "${base || '/'}", noindex=${noindex}.`,
);
